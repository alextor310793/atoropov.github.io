// Пишет сегодняшнюю дату словами, как в начале страницы тетради:
// «Пятое ноября. Классная работа.»
(function () {
  var days = [
    "Первое", "Второе", "Третье", "Четвёртое", "Пятое", "Шестое", "Седьмое",
    "Восьмое", "Девятое", "Десятое", "Одиннадцатое", "Двенадцатое",
    "Тринадцатое", "Четырнадцатое", "Пятнадцатое", "Шестнадцатое",
    "Семнадцатое", "Восемнадцатое", "Девятнадцатое", "Двадцатое",
    "Двадцать первое", "Двадцать второе", "Двадцать третье",
    "Двадцать четвёртое", "Двадцать пятое", "Двадцать шестое",
    "Двадцать седьмое", "Двадцать восьмое", "Двадцать девятое",
    "Тридцатое", "Тридцать первое"
  ];
  var months = [
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря"
  ];
  var el = document.getElementById("today");
  if (!el) return;
  var d = new Date();
  var text = days[d.getDate() - 1] + " " + months[d.getMonth()] + ".";
  el.textContent = text;
  var iso = d.getFullYear() + "-" + String(d.getMonth() + 1).padStart(2, "0") + "-" + String(d.getDate()).padStart(2, "0");
  el.setAttribute("datetime", iso);
})();
